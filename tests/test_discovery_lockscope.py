def test_missing_lock_is_path_dependent_positive(fixture_env):
    s = scope(fixture_env, "fixture_missing_lock")
    row = release_assessment(s)
    assert row["lock_state"]["verdict"] == PATH_DEPENDENT
    assert row["lock_state"]["must"] == []
    assert row["lock_state"]["may"]
    assert row["evidence"]["control_flow_path"]
    assert any(f["pattern"] == "LOCK_SCOPE_PATH_DEPENDENT" for f in s.findings())


def test_correctly_protected_release_is_negative(fixture_env):
    s = scope(fixture_env, "fixture_protected")
    row = release_assessment(s)
    assert row["lock_state"]["verdict"] == HELD
    assert row["lock_state"]["covering_locks"]
    assert not s.findings()


def test_different_lock_object_does_not_cover_mutation(fixture_env):
    s = scope(fixture_env, "fixture_different_lock")
    row = release_assessment(s)
    assert row["lock_state"]["verdict"] == DIFFERENT_LOCK
    assert row["lock_state"]["alternative_locks"]
    assert row["lock_state"]["covering_locks"] == []
    assert any(f["pattern"] == "LOCK_IDENTITY_MISMATCH" for f in s.findings())


def test_aliases_resolve_to_one_lock_identity(fixture_env):
    s = scope(fixture_env, "fixture_alias")
    row = release_assessment(s)
    assert row["lock_state"]["verdict"] == HELD
    assert row["site"]["object"].startswith("obj(rbp")
    assert row["lock_state"]["covering_locks"]
    assert not s.findings()


def test_early_return_releases_every_exit(fixture_env):
    s = scope(fixture_env, "fixture_early_return")
    assert release_assessment(s)["lock_state"]["verdict"] == HELD
    exits = s.exit_states()
    assert len(exits) == 2
    assert all(not e["must"] and not e["may"] for e in exits)
    assert not s.findings()


def test_unknown_call_effect_is_never_not_held(fixture_env):
    s = scope(fixture_env, "fixture_unknown")
    row = release_assessment(s)
    assert row["lock_state"]["verdict"] == UNKNOWN_STATE
    assert row["lock_state"]["unknown_causes"]
    assert not any(f["pattern"] == "LOCK_SCOPE_MUTATION_UNLOCKED" for f in s.findings())


def test_return_object_claim_is_path_sensitive(fixture_env):
    vulnerable = scope(fixture_env, "fixture_claim_missing")
    fixed = scope(fixture_env, "fixture_claim_fixed")
    vrows = vulnerable.mutation_assessments()
    frows = fixed.mutation_assessments()
    assert len(vrows) == len(frows) == 1
    assert vrows[0]["lock_state"]["verdict"] == PATH_DEPENDENT
    assert vrows[0]["lock_state"]["object_claim_may"]
    assert frows[0]["lock_state"]["verdict"] == HELD
    assert frows[0]["lock_state"]["object_claim_must"]


def test_reader_claim_does_not_cover_a_write_mutation(fixture_env):
    s = scope(fixture_env, "fixture_shared_claim_write")
    rows = s.mutation_assessments()
    assert len(rows) == 1
    state = rows[0]["lock_state"]
    assert state["verdict"] == DIFFERENT_LOCK
    assert state["object_claim_must"] == []
    assert state["object_claim_shared_may"]
    assert any(f["pattern"] == "LOCK_IDENTITY_MISMATCH" for f in s.findings())


def test_dominator_evidence_separates_fixed_from_path_dependent(fixture_env):
    fixed = scope(fixture_env, "fixture_claim_fixed").mutation_assessments()[0]
    missing = scope(fixture_env, "fixture_claim_missing").mutation_assessments()[0]
    fixed_dom = fixed["evidence"]["dominators"]["covering"]
    assert fixed_dom and all(row["dominates_mutation"] for row in fixed_dom)
    missing_dom = missing["evidence"]["dominators"]["possibly_covering"]
    assert missing_dom and not any(row["dominates_mutation"] for row in missing_dom)


def test_cfg_extent_excludes_neighbour_functions(fixture_env):
    _doc, image, index, _catalog = fixture_env
    rec = index.by_name("fixture_missing_lock")
    ext = discover_extent(image, rec.rva, cap=256)
    assert ext.capped is False
    assert ext.size == rec.size
    assert len(ext.returns) == 1


def test_entry_reachability_budget_is_sorted_and_reproducible():
    class DummyEntryIndex(EntryIndex):
        def __init__(self):
            pass

        def callees(self, rva):
            return {1000003, 17, 50001} if rva == 1 else set()

    # With a two-node budget, deterministic ordering must always select the
    # smallest callee after the root, independent of set/hash iteration order.
    assert list(DummyEntryIndex().reachable([1], depth=1, budget=2)) == [1, 17]


@pytest.fixture(scope="module")
def lapse_pair_report():
    env = validate.Environment.load(str(ROOT / "tools" / "discovery" / "data"),
                                    only=["13.52", "9.00"])
