def test_lapse_pair_is_resolved_from_sysent_cfg_and_callgraph(lapse_pair_report):
    report = lapse_pair_report
    assert report["mapping_basis"].startswith("sysent entry")
    for fw in ("9.00", "13.52"):
        row = report["firmware"][fw]
        assert row["narg"] == 3
        assert len(row["entry_chain"]) >= 2
        assert row["extent"]["capped"] is False
        assert row["extent"]["returns"]
        assert row["callgraph"]["direct_calls"] > 0
        assert row["catalog"]["coverage"]["decode_errors"] == []
    assert report["firmware"]["9.00"]["body_sha256"] != report["firmware"]["13.52"]["body_sha256"]
    assert report["callee_correspondence"]["pairs"] > 0


def test_d3_discriminates_vulnerable_and_fixed_lapse(lapse_pair_report):
    report = lapse_pair_report
    assert report["verdict"] == "PASS", json.dumps(report.get("acceptance"), indent=2)
    assert report["acceptance"]["vulnerable_positive_findings"] >= 1
    assert report["acceptance"]["fixed_actionable_false_positives"] == 0
    positive = report["acceptance"]["positive"][0]
    assert positive["lock_state"]["verdict"] == PATH_DEPENDENT
    assert positive["evidence"]["control_flow_path"]
    assert positive["site"]["instruction"]
    # Dominator proof: the object claim that would protect this mutation is not
    # on every incoming path, so it must not dominate the mutation block.
    possibly = positive["evidence"]["dominators"]["possibly_covering"]
    assert possibly and not any(row["dominates_mutation"] for row in possibly)
    assert positive["lock_state"]["covering_locks"] == []
    fixed = {fw: row for fw, row in report["firmware"].items() if fw == "13.52"}["13.52"]
    held = [row for row in fixed["assessments"]
            if row["lock_state"]["verdict"] == HELD
            and row["lock_state"]["object_claim_must"]]
    assert held, "the fixed body must carry at least one dominator-proven claim"
    assert all(row["dominates_mutation"]
               for row in held[0]["evidence"]["dominators"]["covering"])
