def document() -> dict:
    return {
        "schema": "ps4rf-experiment-vectors-v1",
        "purpose": "oracle parity: PS4RF experiment layer vs the frozen payload harnesses",
        "oracle": ORACLE,
        "identity_rule": "B marker in a global/latest status region alone is NOT TOCTOU; "
                         "TOCTOU_CONFIRMED needs an A-attributable result containing B-only state",
        "stale_rows": "never computed, never reported by the OWN-1 experiment",
        "vectors": [
            {"scenario": s, "experiment": e, "expected_classification": c, "oracle_log_sha256": h}
            for s, e, c, h in VECTORS
        ],
    }


def canonical_bytes(doc: dict) -> bytes:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=True).encode() + b"\n"


def write(check: bool) -> int:
    data = canonical_bytes(document())
    digest = hashlib.sha256(data).hexdigest()
    if check:
        if not OUT.exists() or OUT.read_bytes() != data:
            print(f"VECTORS DRIFT: {OUT} differs from the generated document")
            return 1
        print(f"vectors OK  sha256={digest[:16]}")
        return 0
    OUT.write_bytes(data)
    recipe_header = ROOT / "native" / "target" / "ps4rf_recipe_data.h"
    recipe_hash = hashlib.sha256(recipe_header.read_bytes()).hexdigest() if recipe_header.exists() else "missing"
    README.write_text(f"""# Experiment vectors (oracle parity)

Generated by `python -m tools.experiments.gen_vectors`; do not edit by hand.

* file: `vectors-v1.json`
* canonical sha256: `{digest}`
* oracle: the frozen payloads Q6LIVE (`{ORACLE['q6live']['sha256'][:16]}...`) and
  OWN1LIVE (`{ORACLE['own1live']['sha256'][:16]}...`) with their archived host-harness logs
  (per-vector `oracle_log_sha256`).
* the PS4RF experiment layer (`tools/experiments/`) must reproduce every
  `expected_classification` for the same simulated state; `tests/test_experiment_parity.py`
  enforces it.
* recipe and command policy values live in `q6-recipe-v3.json` / `own1-recipe-v2.json` /
  `ioctl-policy-v1.json` with provenance to the accepted v4.2 observer and the proven
  pup_update command family.
* recipe-table sha256: `{recipe_hash}` (native/target/ps4rf_recipe_data.h,
  generated by `native/target/gen_recipe.py`)
""")
    print(f"vectors written  sha256={digest}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    return write(ap.parse_args().check)


if __name__ == "__main__":
    raise SystemExit(main())
