_REGISTRY: dict[str, Region] = {region.name: region for region in _REGIONS}


# --- lookup ------------------------------------------------------------------------------

def regions() -> dict[str, Region]:
    """All registered regions keyed by name (a fresh dict; the entries are frozen)."""
    return dict(_REGISTRY)


def get_region(name: str) -> Region | None:
    """The named region, or ``None``; a non-string name resolves to nothing (fail closed)."""
    if not isinstance(name, str):
        return None
    return _REGISTRY.get(name)


def is_strict_source(region: Region) -> bool:
    """True only for ``STRICT_FINGERPRINT`` regions: only they serve identity reads."""
    return region.identity_status == IDENTITY_STRICT


def may_read(region: Region) -> bool:
    """The frozen readability rule.

    ``STRICT_FINGERPRINT`` regions may be read; every other region only when its
    explicit ``policy`` names it as an approved bounded-research region.
    ``STRUCTURAL_ONLY`` is not automatically readable and never a trusted identity
    source; ``UNRESOLVED`` is never readable.
    """
    if region.identity_status == IDENTITY_UNRESOLVED:
        return False
    return region.identity_status == IDENTITY_STRICT \
        or region.policy in READABLE_POLICIES


# --- the target table (what a payload compiles) --------------------------------------------
#
# Two different questions, two different answers -- never interchangeable (deviation
# ``W12-A-D1``: a *compiled* region count was compared against the *policy* total):
#
# * :func:`regions` -- the full policy registry, ``UNRESOLVED`` entries included: the review
#   surface that documents what is registered, what is refused by design and what is not
#   pinned yet;
# * :func:`compiled_regions` -- the normative *target table*: registry order with the
#   ``UNRESOLVED`` entries excluded, exactly what ``native/target/gen_kread_regions.py``
#   compiles into ``ps4rf_kread_regions.h`` and therefore the only correct source for the
#   compiled region count, the target table order, the region index mapping and live
#   payload parity.

def compiled_regions(registry: Sequence[Region] | None = None) -> tuple[Region, ...]:
    """The compiled target table: registry order, ``UNRESOLVED`` policy entries excluded.

    Fails closed (:class:`KReadReject`, ``KREAD_TABLE_INVALID``) when the table cannot be
    trusted: a region registered twice, a non-``UNRESOLVED`` entry that misses any of its
    id/rva/length/policy/provenance, or a table that would compile to nothing. A refused
    entry stays in :func:`regions` -- documentation is not dropped, it is *not compiled*.
    """
    source = _REGIONS if registry is None else tuple(registry)
    seen: set[str] = set()
    table: list[Region] = []
    for region in source:
        if region.name in seen:
            raise KReadReject(KREAD_TABLE_INVALID,
                              f'region {region.name!r} is registered twice; the target table '
                              'must never compile a duplicate')
        seen.add(region.name)
        if region.identity_status == IDENTITY_UNRESOLVED:
            continue
        incomplete = [field for field, value in (('rva', region.rva), ('length', region.length))
                      if not isinstance(value, int) or isinstance(value, bool) or value < 0]
        if incomplete or not region.provenance or region.policy not in POLICY_VALUES:
            raise KReadReject(KREAD_TABLE_INVALID,
                              f'region {region.name!r} is not UNRESOLVED but is incomplete '
                              f"({', '.join(incomplete) if incomplete else 'policy/provenance'})")
        table.append(region)
    if not table:
        raise KReadReject(KREAD_TABLE_INVALID, 'the target table would compile to nothing')
    return tuple(table)


def compiled_region_names(registry: Sequence[Region] | None = None) -> tuple[str, ...]:
    """The target table's region ids in compiled order (the payload's index order)."""
    return tuple(region.name for region in compiled_regions(registry))


def compiled_region_index(name: str, registry: Sequence[Region] | None = None) -> int | None:
    """The index of ``name`` *inside the target table*; ``None`` for everything else.

    A payload reports indices in its compiled table, so a policy ``UNRESOLVED`` entry
    sitting between two compiled entries may never shift an index.
    """
    if not isinstance(name, str):
        return None
    try:
        return compiled_region_names(registry).index(name)
    except ValueError:
        return None


def compiled_table_problems(registry: Sequence[Region] | None = None) -> list[str]:
    """Integrity problems of the target table (empty list == consistent)."""
    problems: list[str] = []
    source = _REGIONS if registry is None else tuple(registry)
    names = [region.name for region in source]
    if len(names) != len(set(names)):
        problems.append('duplicate region name: the target table refuses to compile')
    try:
        table = compiled_regions(source)
    except KReadReject as exc:
        problems.append(f'the target table does not compile: {exc}')
        return problems
    registered = {region.name for region in source}
    for region in table:
        if region.name not in registered:
            problems.append(f'{region.name}: compiled region is not in the policy registry')
        if region.identity_status == IDENTITY_UNRESOLVED:
            problems.append(f'{region.name}: an UNRESOLVED policy entry reached the target table')
        if region.rva is None or region.length is None:
            problems.append(f'{region.name}: a compiled region needs its rva and length')
        if not region.provenance:
            problems.append(f'{region.name}: a compiled region needs its provenance')
        if not may_read(region):
            problems.append(f'{region.name}: a compiled region must satisfy the readability rule')
    if len({region.name for region in table}) != len(table):
        problems.append('a region was compiled twice')
    if not table:
        problems.append('the target table is empty')
    return problems


# --- resolution --------------------------------------------------------------------------

def resolve_read(region_name: str, offset: int, length: int,
                 *, structural_only: bool = False) -> ResolvedRead:
    """Resolve one bounded read inside a registered region; every refusal names its reason.

    The default read needs a STRICT identity source (the reads this framework performs
    exist to establish identity). ``structural_only=True`` declares the read an
    observation of a ``STRUCTURAL_ONLY`` region (e.g. ``aperture_global``) -- the only
    form in which such a region is readable. ``UNRESOLVED`` regions are never readable,
    with or without the flag.

    Check order (frozen; each step owns exactly the failure it must own):

    ==================================== =================================================
    ``KREAD_UNKNOWN_REGION``             the name is not registered -- no raw fallback
    ``KREAD_UNRESOLVED_REGION``          registered, but pinned by no evidence -- no read
    ``KREAD_POLICY_NOT_APPROVED``        no read approval and not a strict region
    ``KREAD_STRICT_IDENTITY_REQUIRED``   read needs STRICT identity, region is not STRICT
    ``KREAD_NEGATIVE_OFFSET``            ``offset < 0``
    ``KREAD_OFFSET_OVERFLOW``            ``offset + length`` does not fit unsigned 64 bits
    ``KREAD_LENGTH_ZERO``                ``length < 1`` (a zero-byte read is no measurement)
    ``KREAD_LENGTH_EXCEEDS_MAX``         ``length > MAX_READ_LEN`` (one read is bounded)
    ``KREAD_CROSS_REGION``               ``offset + length`` leaves the region
    ``KREAD_NON_CANONICAL_ADDRESS``      ``rva + offset`` is not a canonical 48-bit address
    ==================================== =================================================
    """
    region = get_region(region_name)
    if region is None:
        raise KReadReject(KREAD_UNKNOWN_REGION,
                          f'region {region_name!r} is not in the registry')
    if region.identity_status == IDENTITY_UNRESOLVED or region.rva is None \
            or region.length is None:
        raise KReadReject(KREAD_UNRESOLVED_REGION,
                          f'region {region.name!r} is registered {IDENTITY_UNRESOLVED}: '
                          'no read is admissible')
    if not may_read(region):
        raise KReadReject(KREAD_POLICY_NOT_APPROVED,
                          f'region {region.name!r} ({region.identity_status}, policy '
                          f'{region.policy!r}) may not be read: only STRICT_FINGERPRINT '
                          'regions or explicitly approved bounded-research regions are '
                          'readable')
    if not structural_only and not is_strict_source(region):
        raise KReadReject(
            KREAD_STRICT_IDENTITY_REQUIRED,
            f'region {region.name!r} is {region.identity_status}: not a STRICT identity '
            'source for a read that needs one (an explicit structural-only observation '
            'request is the only readable form)')
    if isinstance(offset, bool) or not isinstance(offset, int) \
            or isinstance(length, bool) or not isinstance(length, int):
        raise KReadReject(KREAD_SCHEMA_TYPE, 'offset and length must be integers')
    if offset < 0:
        raise KReadReject(KREAD_NEGATIVE_OFFSET, f'offset {offset} is negative')
    end = checked_add(offset, length)
    if end is None:
        raise KReadReject(KREAD_OFFSET_OVERFLOW,
                          f'offset {offset} + length {length} does not fit unsigned 64 bits')
    if length < 1:
        raise KReadReject(KREAD_LENGTH_ZERO, 'length must be at least 1')
    if length > MAX_READ_LEN:
        raise KReadReject(KREAD_LENGTH_EXCEEDS_MAX,
                          f'length {length} exceeds the {MAX_READ_LEN} byte read maximum')
    if end > region.length:
        raise KReadReject(KREAD_CROSS_REGION,
                          f'offset {offset} + length {length} reaches byte {end}, past '
                          f'region {region.name!r} ({region.length} bytes)')
    address = checked_add(region.rva, offset)
    if address is None or not is_canonical_x86_64(address):
        raise KReadReject(KREAD_NON_CANONICAL_ADDRESS,
                          f'rva {region.rva} + offset {offset} is not a canonical '
                          '48-bit address')
    return ResolvedRead(address=address, rva=region.rva, offset=offset, length=length,
                        region=region)


@dataclass(frozen=True)
class ResolvedRuntimeRead:
    """A relative window resolved against the *current* boot's kernel base (W12-RVA0-BINDING).

    ``runtime_base_va`` is the region's runtime base (``kernel base + rva``: for
    ``image_elf`` this is the kernel base itself, because its rva is 0) and
    ``runtime_address`` is the addressed byte (``kernel base + rva + offset``). Both are
    checked sums of this boot's binding - neither is a profile fact.
    """

    kbase: int
    rva: int
    offset: int
    length: int
    runtime_base_va: int
    runtime_address: int
    region: Region


def checked_kernel_address(kbase: int, rva: int) -> int:
    """``checked_add(kbase, rva)`` under the runtime rules (W12-RVA0-BINDING).

    The relative value (``rva``) may be 0 -- that is what makes it a locator. The *result*
    is a runtime address and must therefore be non-zero and canonical; an overflow refuses
    the read. Fail closed, named reasons. This is the one implementation of the rule: the
    bounded-read resolution (:func:`resolve_runtime`) and the W5 runtime binding
    (``tools.profiles.binding.create_runtime_binding``) both go through it.
    """
    if not isinstance(kbase, int) or isinstance(kbase, bool) or kbase < 0:
        raise KReadReject(KREAD_SCHEMA_TYPE, f'kernel base {kbase!r} is not an address')
    if not isinstance(rva, int) or isinstance(rva, bool) or rva < 0:
        raise KReadReject(KREAD_SCHEMA_TYPE, f'rva {rva!r} is not a relative position')
    if kbase == 0:
        raise KReadReject(KREAD_ZERO_RUNTIME_ADDRESS,
                          'the kernel base is 0: a runtime base of 0 is not a binding')
    runtime_va = checked_add(kbase, rva)
    if runtime_va is None:
        raise KReadReject(KREAD_RUNTIME_OVERFLOW,
                          f'kernel base {kbase:#x} + rva {rva:#x} does not fit unsigned 64 bits')
    if runtime_va == 0:
        raise KReadReject(KREAD_ZERO_RUNTIME_ADDRESS,
                          'the resolved runtime address is 0: an rva of 0 is a valid locator, '
                          'a runtime address of 0 is not')
    if not is_canonical_x86_64(runtime_va):
        raise KReadReject(KREAD_NON_CANONICAL_ADDRESS,
                          f'the resolved runtime address (kernel base + rva) {runtime_va:#x} is '
                          'not a canonical 48-bit address')
    return runtime_va


def resolve_runtime(resolved: ResolvedRead, kbase: int) -> ResolvedRuntimeRead:
    """Attach the current boot's kernel base to a relative window; checked, fail closed.

    Check order (each step owns exactly the failure it must own):

    ==================================== =================================================
    ``KREAD_SCHEMA_TYPE``                ``kbase`` is not a non-negative integer
    ``KREAD_RUNTIME_OVERFLOW``           ``kbase + rva`` (or ``+ offset``) leaves u64
    ``KREAD_ZERO_RUNTIME_ADDRESS``       the resolved runtime address is 0 (not an address)
    ``KREAD_NON_CANONICAL_ADDRESS``      the resolved value is not a canonical x86-64 VA
    ``KREAD_OUTSIDE_IMAGE_WINDOW``       the window leaves the pinned kernel image window
    ==================================== =================================================

    The *relative* value (the rva) is deliberately not re-validated here: it was validated
    as a locator, where zero is a valid image position. This function validates only what
    the runtime binding makes of it - and a runtime address is never 0.
    """
    if not isinstance(kbase, int) or isinstance(kbase, bool) or kbase < 0:
        raise KReadReject(KREAD_SCHEMA_TYPE, f'kernel base {kbase!r} is not an address')
    runtime_base_va = checked_kernel_address(kbase, resolved.rva)
    runtime_address = checked_add(runtime_base_va, resolved.offset)
    if runtime_address is None:
        raise KReadReject(KREAD_RUNTIME_OVERFLOW,
                          f'resolved address {runtime_base_va:#x} + offset '
                          f'{resolved.offset:#x} does not fit unsigned 64 bits')
    if runtime_address == 0:
        raise KReadReject(KREAD_ZERO_RUNTIME_ADDRESS,
                          'the resolved window address is 0: an rva of 0 is a valid locator, '
                          'a runtime address of 0 is not')
    if not is_canonical_x86_64(runtime_address):
        raise KReadReject(KREAD_NON_CANONICAL_ADDRESS,
                          f'the resolved window address (kernel base + rva + offset) '
                          f'{runtime_address:#x} is not a canonical 48-bit address')
    end_rva = checked_add(checked_add(resolved.rva, resolved.offset), resolved.length)
    if end_rva is None or end_rva > IMAGE_WINDOW_MAX_RVA:
        raise KReadReject(KREAD_OUTSIDE_IMAGE_WINDOW,
                          f'rva {resolved.rva:#x} + offset {resolved.offset} + length '
                          f'{resolved.length} leaves the pinned image window '
                          f'({IMAGE_WINDOW_MAX_RVA:#x})')
    return ResolvedRuntimeRead(kbase=kbase, rva=resolved.rva, offset=resolved.offset,
                               length=resolved.length, runtime_base_va=runtime_base_va,
                               runtime_address=runtime_address, region=resolved.region)


# --- integrity ---------------------------------------------------------------------------

def registry_problems() -> list[str]:
    """Integrity problems of the frozen registry (empty list == consistent).

    Pins what must never silently change: names, provenance (they must exist), the
    fail-closed representation of ``UNRESOLVED`` entries, the image-window and canonical
    bounds, the readability rule, the identity policy special case ``aperture_global``
    and the STRICT membership of every proven read region.
    """
    problems: list[str] = []
    names = [region.name for region in _REGIONS]
    if len(names) != len(set(names)):
        problems.append('duplicate region name')
    for region in _REGIONS:
        if not region.name or not isinstance(region.name, str):
            problems.append('every region needs a non-empty name')
        if region.identity_status not in IDENTITY_STATUSES:
            problems.append(f'{region.name}: unknown identity_status {region.identity_status!r}')
        if region.policy not in POLICY_VALUES:
            problems.append(f'{region.name}: unknown policy {region.policy!r}')
        if not region.notes.strip():
            problems.append(f'{region.name}: no provenance notes')
        if not region.profile_requirement.strip():
            problems.append(f'{region.name}: no profile_requirement stated')
        if not region.provenance or not all(isinstance(s, str) and s
                                            for s in region.provenance):
            problems.append(f'{region.name}: every region must name its source files')
        for source in region.provenance:
            if not (REPO_ROOT / source).is_file():
                problems.append(f'{region.name}: source {source!r} does not exist')
        if region.identity_status == IDENTITY_UNRESOLVED:
            if region.rva is not None or region.length is not None:
                problems.append(f'{region.name}: UNRESOLVED regions must not carry '
                                'a usable rva/length')
            if region.policy != POLICY_NOT_APPROVED:
                problems.append(f'{region.name}: UNRESOLVED regions must not claim a '
                                'read policy')
            if may_read(region):
                problems.append(f'{region.name}: UNRESOLVED regions must never be readable')
            continue
        if not isinstance(region.rva, int) or isinstance(region.rva, bool) or region.rva < 0:
            problems.append(f'{region.name}: rva must be a non-negative integer')
            continue
        if not isinstance(region.length, int) or isinstance(region.length, bool) \
                or region.length < 1:
            problems.append(f'{region.name}: length must be an integer >= 1')
            continue
        if not is_canonical_x86_64(region.rva):
            problems.append(f'{region.name}: rva is not a canonical address')
        if region.rva + region.length > IMAGE_WINDOW_MAX_RVA:
            problems.append(f'{region.name}: rva + length leaves the 64 MiB pinned '
                            'image window')
        if not may_read(region):
            problems.append(f'{region.name}: a pinned region must satisfy the readability '
                            'rule (strict, or an approved bounded-research policy)')
        if region.max_size != region.length:
            problems.append(f'{region.name}: max_size must be the region length')
    aperture = _REGISTRY.get('aperture_global')
    if aperture is None:
        problems.append('aperture_global must be registered (STRUCTURAL_ONLY)')
    else:
        if aperture.identity_status != IDENTITY_STRUCTURAL_ONLY:
            problems.append('aperture_global must be STRUCTURAL_ONLY (unstable across '
                            'captures)')
        if is_strict_source(aperture):
            problems.append('aperture_global must never be a STRICT identity source')
        if aperture.policy != POLICY_APPROVED_BOUNDED_RESEARCH:
            problems.append('aperture_global must stay under the approved bounded-research '
                            'policy (observation only)')
    pool = _REGISTRY.get('keymgr_pool')
    if pool is None:
        problems.append('keymgr_pool must be registered (STRUCTURAL_ONLY, W16)')
    else:
        if pool.identity_status != IDENTITY_STRUCTURAL_ONLY:
            problems.append('keymgr_pool must be STRUCTURAL_ONLY: the slot pool bytes are '
                            'runtime state, never a byte fingerprint')
        if is_strict_source(pool):
            problems.append('keymgr_pool must never be a STRICT identity source')
        if pool.policy != POLICY_APPROVED_BOUNDED_RESEARCH:
            problems.append('keymgr_pool must stay under the approved bounded-research policy '
                            '(observation only)')
    # Track A observation set: every region carrying the observation provenance must be a pinned
    # STRUCTURAL_ONLY observation -- runtime state, never an identity source, never UNRESOLVED,
    # its length inside the global read bound -- and the set must not be empty. The set is what
    # the payload's fixed step reads: one window per session, selected by this provenance alone.
    if not any(A_OBS_PROVENANCE[0] in region.provenance for region in _REGIONS):
        problems.append('the Track A observation set (provenance '
                        f'{A_OBS_PROVENANCE[0]!r}) must not be empty')
    for region in _REGIONS:
        if A_OBS_PROVENANCE[0] not in region.provenance:
            continue
        if region.identity_status != IDENTITY_STRUCTURAL_ONLY:
            problems.append(f'{region.name}: an observation window must be STRUCTURAL_ONLY '
                            '(runtime state, never an identity source)')
        if is_strict_source(region):
            problems.append(f'{region.name}: an observation window must never be a STRICT '
                            'identity source')
        if region.rva is None or region.length is None:
            problems.append(f'{region.name}: an observation window must be pinned '
                            '(rva and length)')
            continue
        if region.length > MAX_READ_LEN:
            problems.append(f'{region.name}: observation length {region.length} exceeds '
                            f'MAX_READ_LEN {MAX_READ_LEN}')
        if region.policy != POLICY_APPROVED_BOUNDED_RESEARCH:
            problems.append(f'{region.name}: an observation window must stay under the approved '
                            'bounded-research policy')
    for name in ('image_elf', 'amd_iommu', 'gbase_vtophys', 'code_anchor', 'xfast_entry',
                 'copyout_prologue', 'prison0_static', 'boottime',
                 'ccp_submit_entry', 'ccp_device_gate', 'keymgr_claim_entry',
                 'keymgr_bind_entry', 'keymgr_release_entry'):
        region = _REGISTRY.get(name)
        if region is None or region.identity_status != IDENTITY_STRICT:
            problems.append(f'{name} must be registered STRICT_FINGERPRINT')
    if MAX_READ_LEN != 4096:
        problems.append('MAX_READ_LEN must stay 4096')
    return problems


def registry_report() -> dict:
    """Machine-readable registry matrix (the ``--matrix`` output)."""
    return {
        'wave': 'W12',
        'max_read_len': MAX_READ_LEN,
        'identity_statuses': list(IDENTITY_STATUSES),
        'policies': list(POLICY_VALUES),
        'readable_policies': list(READABLE_POLICIES),
        'image_window_max_rva': hex(IMAGE_WINDOW_MAX_RVA),
        'regions': [
            {
                'name': region.name,
                'rva': None if region.rva is None else hex(region.rva),
                'length': region.length,
                'max_size': region.max_size,
                'identity_status': region.identity_status,
                'policy': region.policy,
                'provenance': list(region.provenance),
                'locator': region.locator,
                'profile_requirement': region.profile_requirement,
                'may_read': may_read(region),
                'notes': region.notes,
            }
            for region in _REGIONS
        ],
    }


def main(argv: list[str]) -> int:
    if '--matrix' in argv:
        print(json.dumps(registry_report(), indent=1, sort_keys=True))
        return 0
    if '--self-test' in argv:
        problems = registry_problems() + compiled_table_problems()
        for problem in problems:
            print(f'regions: {problem}')
        if not problems:
            table = compiled_regions()
            print(f'regions self-test: {len(_REGIONS)} policy entries, '
                  f'{len(table)} compiled for the payload, max read {MAX_READ_LEN} (ok)')
        else:
            print(f'regions self-test: {len(_REGIONS)} policy entries, max read {MAX_READ_LEN} '
                  '(FAILED)')
        return 0 if not problems else 1
    print((__doc__ or '').strip().splitlines()[0])
    print('usage: regions.py --self-test | --matrix')
    return 2


