#!/usr/bin/env python3
"""W12 ``kernel.read`` region registry: the approved READ-ONLY regions of pinned FW13.52.

Every entry here is *evidence*, never invention, and every entry names the files its
numbers come from in :attr:`Region.provenance`. The W9 attestation windows come from
``native/target/ps4rf_attest_data.h`` (generated by ``native/target/gen_attest_table.py``
from the pinned kernel image) as promoted into ``profiles/fw1352/profile-13.52.json``;
the W11.2 boottime region is the single fixed window of the privileged boot read
(``native/target/ps4rf_bootread.c``/.h, ``profiles/fw1352/boot-identity.json``, restated
host side in ``tools/hostctl/bootpriv.py``); the W16 CCP/keymgr binding windows come from the
revision candidate ``profiles/fw1352/profile-13.52-ccp1.json`` plus ``profiles/fw1352/
ccp-layouts.json`` (both cite the pinned kernel image as their source), whose promotion
precondition is the live byte-match of exactly these windows
(``docs/P4-CCP-ACCEPTANCE-REQ.md``, section 7).

Representation note: ``rva``/``length`` are decimal integers, exactly as
``profiles/fw1352/profile-13.52.json`` stores the same locator values; the evidence files
name them in hex. The W5 artifact guard (``tests/test_profile_binding.py::
test_w5_artifacts_contain_no_real_looking_addresses``) admits no ``0x``-prefixed hex
literal of six or more digits in this layer, so the registry states the numbers in the
profile's own representation and ``tests/test_regions.py`` re-reads the hex values out of
the evidence files to pin every single number to its source.

Region fields (what every entry carries):

* ``name`` -- the region id a request names in its ``region`` key;
* ``rva`` -- image-relative offset of the window (runtime address = kbase + rva);
* ``length`` -- the window size and the hard cap of any single read into it: a region's
  ``length`` is its ``max_size`` (see :attr:`Region.max_size`), and ``offset + length <=
  region.length`` is enforced by :func:`resolve_read`;
* ``identity_status`` -- ``STRICT_FINGERPRINT`` (byte-matched against the pinned image,
  may serve as an identity source), ``STRUCTURAL_ONLY`` (observation only, never a
  trusted identity source) or ``UNRESOLVED``;
* ``policy`` -- the explicit read approval. Readability rule, strictly: only
  ``STRICT_FINGERPRINT`` regions, or regions whose policy is
  ``APPROVED_BOUNDED_RESEARCH``, may be read at all. ``STRUCTURAL_ONLY`` is *not*
  automatically readable -- it needs the explicit approved bounded-research policy and it
  may never serve as a trusted identity source. ``UNRESOLVED`` is never readable;
* ``provenance`` -- the source files the entry's numbers come from (repo-relative paths);
* ``locator`` -- the W5 profile locator / region identifier this entry binds to;
* ``profile_requirement`` -- what the active profile must satisfy for this region;
* ``notes`` -- review context (why the status, what stays open).

``aperture_global`` is ``STRUCTURAL_ONLY`` by agreement: its value is boot dependent
(pinned image and phase-9 live values differ), so it is never a byte fingerprint, must
not silently become a trusted read region, and is readable only as an explicit
structural observation (``structural_only=True``) under the approved policy.

Rules kept by construction:

* no entry points into the direct map (DMAP) or page tables: the evidence names none, and
  every pinned rva sits inside the 64 MiB pinned image window
  (``IMAGE_WINDOW_MAX_RVA``), so a physical-map address (far outside) is not expressible;
* W6/differential findings never auto-enter the registry -- an entry needs the explicit
  W5/profile review path, exactly like the profile promotion;
* the request can never name a raw address: the caller names a region and the resolved
  address is computed here (``rva + offset``) and returned inside ``ResolvedRead``.

Bounds, in the frozen order (each check owns exactly one failure): unknown region ->
unresolved region -> policy not approved -> strict-identity required -> negative offset ->
64-bit checked ``offset + length`` overflow -> length zero -> length above ``MAX_READ_LEN``
-> cross-region -> non-canonical resolved address. Both sums go through
:func:`tools.profiles.kread.checked_add`, so no wrap can pass unnoticed.

Usage::

    python tools/profiles/regions.py --self-test
    python tools/profiles/regions.py --matrix
"""

