#: registry out of DMAP and the page tables, which the evidence does not name as sources.
IMAGE_WINDOW_MAX_RVA = 64 * 1024 * 1024


@dataclass(frozen=True)
class Region:
    """One approved read region: identity status, read policy, evidence and binding.

    ``rva``/``length`` are ``None`` exactly for ``UNRESOLVED`` regions: an entry that
    cannot be pinned carries no usable number and every read on it is refused before
    arithmetic starts. Pinned entries hold the exact numbers their ``provenance`` states.

    A region's ``length`` is its ``max_size``: the hard cap of any single read into it
    (see the :attr:`max_size` property). The global ceiling on top of that is
    :data:`MAX_READ_LEN`.
    """

    name: str
    rva: int | None
    length: int | None
    identity_status: str
    policy: str
    provenance: tuple[str, ...]
    locator: str | None
    profile_requirement: str
    notes: str

    def __post_init__(self) -> None:
        """Fail closed on a malformed entry (vocabulary and types, not ranges)."""
        if not isinstance(self.name, str) or not self.name:
            raise ValueError('region name must be a non-empty string')
        if self.identity_status not in IDENTITY_STATUSES:
            raise ValueError(f'unknown identity_status {self.identity_status!r}')
        if self.policy not in POLICY_VALUES:
            raise ValueError(f'unknown policy {self.policy!r}')
        if not isinstance(self.provenance, tuple) \
                or not all(isinstance(source, str) and source for source in self.provenance):
            raise ValueError('provenance must be a tuple of non-empty source paths')
        for value, field in ((self.rva, 'rva'), (self.length, 'length')):
            if value is not None and (isinstance(value, bool) or not isinstance(value, int)):
                raise ValueError(f'{field} must be an integer or None')
        if self.locator is not None and (not isinstance(self.locator, str) or not self.locator):
            raise ValueError('locator must be a non-empty string or None')
        if not isinstance(self.profile_requirement, str):
            raise ValueError('profile_requirement must be a string')
        if not isinstance(self.notes, str):
            raise ValueError('notes must be a string')

    @property
    def max_size(self) -> int | None:
        """Hard cap of one read into this region: ``length`` itself.

        A read may never cross a region, so the region's own length is the maximum
        admissible read size; :data:`MAX_READ_LEN` bounds every single read globally.
        ``None`` for ``UNRESOLVED`` regions (nothing is readable there).
        """
        return self.length

    @property
    def sources(self) -> tuple[str, ...]:
        """Alias of :attr:`provenance` (the files the entry's numbers come from)."""
        return self.provenance


@dataclass(frozen=True)
class ResolvedRead:
    """A read that passed every bound: internal address ``rva + offset``, still unslid.

    ``address`` is the resolved internal address (the provider adds the boot's kernel
    base). It exists only here -- a request never carries one.
    """

    address: int
    rva: int
    offset: int
    length: int
    region: Region


