#!/usr/bin/env python3
"""Generate the W9 attestation table (``ps4rf_attest_data.h``) from pinned FW13.52 evidence.

Nothing here is invented: every expected byte comes from the pinned kernel image
(``kernel.bin``, sha256 recorded) and every RVA's live usability is referenced to the phase-9
live run that matched all three anchors byte-exact on this console class. The generated header
carries the provenance in its comments so the payload source never has to restate it.

Usage:
    PS4RF_KERNEL_IMAGE=/path/kernel.bin gen_attest_table.py --write
    PS4RF_KERNEL_IMAGE=/path/kernel.bin gen_attest_table.py --check     # gate
    gen_attest_table.py --self-test                                      # no image needed

The table is fixed: 7 entries, all addresses compile-time constants. No fingerprint may be
added without a new image hash + a live reference, which is why the generator refuses an image
whose sha256 is not the pinned one unless ``--allow-other-image`` is passed (and then it
records the other hash instead of pretending it is the pinned one).
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / 'ps4rf_attest_data.h'
DEFAULT_IMAGE = pathlib.Path(
    '/home/hermes/audits/playstation-ps4/fw1352-ps4b-20260920/kernel-dump/kernel.bin')
PINNED_IMAGE_SHA256 = 'cf157ffdbae872a20bbb9a46c8518b53d96c1ed75d4e73878466a295d92eca35'
STATIC_BASE = 0xFFFFFFFFD00D0000          # image base the pinned dump is relocated for
PHASE9_REF = ('socscope-fw1352-phase9-20260928 '
              '(socscope9-20260928T114307-me-addrbits.json, A1/A2/A3 match: true)')

# id, rva, length, kind, evidence note
ENTRIES = [
    ('image_elf', 0x0, 16, 'static', 'strict',
     'kernel image identity: ELF header at the image base (read at kbase_candidate)'),
    ('amd_iommu', 0x7CE9E9, 16, 'static', 'strict',
     'phase-9 anchor A1 (AMD IOMMU string table)'),
    ('gbase_vtophys', 0x815BBC, 16, 'static', 'strict',
     'phase-9 anchor A2 (Sony gbase_vtophys)'),
    ('code_anchor', 0x4CF6A0, 24, 'static', 'strict',
     'phase-9 anchor A3 (code, gbase_vtophys region)'),
    ('xfast_entry', 0x1C0, 8, 'static', 'strict',
     'SDK fw_defines.h K1352_XFAST_SYSCALL 0x1C0: LSTAR must point here'),
    ('copyout_prologue', 0x2BD6A0, 8, 'static', 'strict', 'SDK fw_defines.h K1352_COPYOUT'),
    ('prison0_static', 0x111FA18, 8, 'relocated', 'strict',
     'SDK fw_defines.h K1352_PRISON_0; image holds the unslid pointer value'),
    ('aperture_global', 0x23D3DF8, 8, 'structural', 'structural',
     'aperture global: STRUCTURAL_ONLY (canonical, >= KERNEL_MIN, 16-aligned observation); '
     'its value is boot dependent: the pinned image stores 0xffff82dae4800000 while the '
     'phase-9 live run observed 0xffffe26de4800000, so it is deliberately NOT a byte fingerprint '
     'and never part of the strict score'),
]

HEADER = '''/* Generated by gen_attest_table.py - do not edit by hand.
 *
 * W9 read-only kernel attestation table.
 *
 * image:    {image_path}
 * sha256:   {image_sha}{image_note}
 * static base the image is relocated for: 0x{static_base:016X}
 * live reference: {phase9}
 *
 * Every entry is a compile-time constant. The kernel callback takes no address from the
 * host: it reads only these RVAs (relative to the LSTAR-derived kernel base candidate) and
 * writes results into the caller's own info block.
 */

#ifndef PS4RF_ATTEST_DATA_H
#define PS4RF_ATTEST_DATA_H

#include <stdint.h>

#define PS4RF_ATTEST_ENTRY_COUNT {count}u

/* kind: how the window is compared. */
#define PS4RF_ATTEST_KIND_STATIC      0u   /* byte-exact fingerprint */
#define PS4RF_ATTEST_KIND_RELOCATED   1u   /* image value + slide must match */
#define PS4RF_ATTEST_KIND_STRUCTURAL  2u   /* only range/alignment gates apply */

/* policy: what a result may do. Two values only, machine readable, one per window.
 *
 * STRICT_FINGERPRINT  observed bytes must equal the pinned expected value (relocated windows:
 *                     the pinned value plus the LSTAR-derived slide). A mismatch stops the
 *                     attestation; only these windows (plus the LSTAR/kbase shape and the
 *                     cross checks) may ever support a PROFILE_MATCH_CANDIDATE decision.
 * STRUCTURAL_ONLY     measured and reported as an observation. Never counts towards the strict
 *                     score, never on its own produces PROFILE_AMBIGUOUS or FAILED, and the
 *                     host verifier must not claim an exact match for it.
 */
#define PS4RF_ATTEST_POLICY_STRICT_FINGERPRINT 0u
#define PS4RF_ATTEST_POLICY_STRUCTURAL_ONLY    1u

#define PS4RF_ATTEST_MAX_LEN {max_len}u

/* Ids are inline char arrays on purpose: a ``const char *`` would need an R_X86_64_RELATIVE
 * relocation in .data.rel.ro, and the artefact must contain no relocation at all. */
#define PS4RF_ATTEST_ID_MAX 24u

typedef struct {{
  char id[PS4RF_ATTEST_ID_MAX];
  uint32_t rva;
  uint32_t len;
  uint32_t kind;
  uint32_t policy;                       /* STRICT_FINGERPRINT | STRUCTURAL_ONLY */
  uint8_t expected[PS4RF_ATTEST_MAX_LEN];
}} ps4rf_attest_entry;

static const ps4rf_attest_entry PS4RF_ATTEST_TABLE[PS4RF_ATTEST_ENTRY_COUNT] = {{
{rows}}};

#endif /* PS4RF_ATTEST_DATA_H */
'''


def build_table(image: pathlib.Path):
    blob = image.read_bytes()
    rows = []
    max_len = 0
    for name, rva, length, kind, policy, note in ENTRIES:
        got = blob[rva:rva + length]
        if len(got) != length:
            raise SystemExit(f'{name}: image too short for rva 0x{rva:x} len {length}')
        max_len = max(max_len, length)
        bytes_c = ', '.join(f'0x{b:02x}' for b in got)
        pad = ', '.join('0x00' for _ in range(max_len - length))
        kind_const = {'static': 'PS4RF_ATTEST_KIND_STATIC',
                      'relocated': 'PS4RF_ATTEST_KIND_RELOCATED',
                      'structural': 'PS4RF_ATTEST_KIND_STRUCTURAL'}[kind]
        policy_const = {'strict': 'PS4RF_ATTEST_POLICY_STRICT_FINGERPRINT',
                        'structural': 'PS4RF_ATTEST_POLICY_STRUCTURAL_ONLY'}[policy]
        id_chars = ', '.join(f"'{c}'" for c in name) + ", '\\0'"
        rows.append(f'  /* {name}: {policy.upper()} - {note} */\n'
                    f'  {{ {{ {id_chars} }}, 0x{rva:X}u, {length}u, {kind_const}, '
                    f'{policy_const}, '
                    f'{{ {bytes_c}' + (f', {pad}' if pad else '') + ' } },')
    return '\n'.join(rows), max_len


def render(image: pathlib.Path, allow_other: bool) -> str:
    digest = hashlib.sha256(image.read_bytes()).hexdigest()
    note = ''
    if digest != PINNED_IMAGE_SHA256:
        if not allow_other:
            raise SystemExit(f'image sha256 {digest} is not the pinned FW13.52 image '
                             f'{PINNED_IMAGE_SHA256} (pass --allow-other-image to record it)')
        note = '  (NOT the pinned image: recorded as is, expectations follow this file)'
    rows, max_len = build_table(image)
    return HEADER.format(image_path=image, image_sha=digest, image_note=note,
                         static_base=STATIC_BASE, phase9=PHASE9_REF,
                         count=len(ENTRIES), max_len=max_len, rows=rows)


def self_test() -> int:
    """Checks that hold without the image: unique ids/rvas, sizes, bounds."""
    problems = []
    ids = [e[0] for e in ENTRIES]
    if len(set(ids)) != len(ids):
        problems.append('duplicate entry id')
    rvas = [e[1] for e in ENTRIES]
    if len(set(rvas)) != len(rvas):
        problems.append('duplicate rva')
    for name, rva, length, kind, policy, note in ENTRIES:
        if kind not in ('static', 'relocated', 'structural'):
            problems.append(f'{name}: bad kind {kind}')
        if policy not in ('strict', 'structural'):
            problems.append(f'{name}: bad policy {policy}')
        # policy and kind must agree: a structural kind can only ever be STRUCTURAL_ONLY, and
        # only STRUCTURAL_ONLY windows are outside the strict score
        if (kind == 'structural') != (policy == 'structural'):
            problems.append(f'{name}: kind {kind} contradicts policy {policy}')
        if policy == 'strict' and kind == 'structural':
            problems.append(f'{name}: structural kind must not be a strict fingerprint')
        if length > 64:
            problems.append(f'{name}: length {length} above the 64 byte cap')
        if rva == 0 and name != 'image_elf':
            problems.append(f'{name}: rva 0 is reserved for the image identity')
        if rva > 0x4000000:
            problems.append(f'{name}: rva outside the 64 MiB image window')
        if not note:
            problems.append(f'{name}: no evidence note')
        if len(name) + 1 > 24:
            problems.append(f'{name}: id longer than PS4RF_ATTEST_ID_MAX')
        if kind == 'relocated' and length != 8:
            problems.append(f'{name}: relocated entries must be exactly 8 bytes')
    # the LSTAR relation must be consistent with the SDK constant
    xfast = [e for e in ENTRIES if e[0] == 'xfast_entry']
    if not xfast or xfast[0][1] != 0x1C0:
        problems.append('xfast_entry must be RVA 0x1C0 (SDK K1352_XFAST_SYSCALL)')
    struct_only = [e[0] for e in ENTRIES if e[4] == 'structural']
    if struct_only != ['aperture_global']:
        problems.append(f'unexpected STRUCTURAL_ONLY entries: {struct_only}')
    strict = [e[0] for e in ENTRIES if e[4] == 'strict']
    if len(strict) != 7:
        problems.append(f'expected 7 STRICT_FINGERPRINT windows, found {len(strict)}')
    hard = {e[0] for e in ENTRIES if e[4] == 'strict'}
    for required in ('image_elf', 'amd_iommu', 'gbase_vtophys', 'code_anchor', 'xfast_entry',
                     'copyout_prologue', 'prison0_static'):
        if required not in hard:
            problems.append(f'{required} must be STRICT_FINGERPRINT')
    for p in problems:
        print(f'SELF-TEST FAIL: {p}')
    print(f'self-test: {len(ENTRIES)} entries, {len(problems)} problem(s)')
    return 1 if problems else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--self-test', action='store_true')
    ap.add_argument('--image', default=str(DEFAULT_IMAGE))
    ap.add_argument('--allow-other-image', action='store_true')
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()
    image = pathlib.Path(args.image)
    if not image.exists():
        print(f'image not found: {image}', file=sys.stderr)
        return 2
    text = render(image, args.allow_other_image)
    if args.write:
        OUT.write_text(text)
        print(f'wrote {OUT} ({len(text)} bytes) from {image}')
        return 0
    if args.check:
        current = OUT.read_text() if OUT.exists() else ''
        if current != text:
            print('ps4rf_attest_data.h is NOT up to date with the pinned image', file=sys.stderr)
            return 1
        print('ps4rf_attest_data.h: up to date with the pinned image')
        return 0
    print(text[:2000])
    return 0


if __name__ == '__main__':
    sys.exit(main())
