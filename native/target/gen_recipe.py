"""Generate the bounded-snapshot recipe table (compile-time profile data).

Usage:  python native/target/gen_recipe.py [--check]

Writes ``native/target/ps4rf_recipe_data.h`` and refreshes the recipe pin in
``tests/fixtures/experiments/README.md``. ``--check`` regenerates in memory and
compares byte for byte (the drift detector).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
OUT = REPO / "native" / "target" / "ps4rf_recipe_data.h"
README = REPO / "tests" / "fixtures" / "experiments" / "README.md"

TYPE_IDS = {"RVA_READ": 1, "FOLLOW_ONCE": 2}
FLAG_ATTACH_GATE = 1
INDEX_NAMES = {"idx_bitmap_word": 1, "idx_ptslot": 2}
INDEX_STRIDE = 8


def _ident(name: str) -> str:
    return name.upper().replace("-", "_")


def render() -> str:
    from tools.profiles.experiment_recipes import all_recipes

    recipes = all_recipes()
    names = list(recipes)
    lines = [
        "/* generated by native/target/gen_recipe.py -- do not edit */",
        "#ifndef PS4RF_RECIPE_DATA_H",
        "#define PS4RF_RECIPE_DATA_H",
        "",
        "#include \"ps4rf_recipe.h\"",
        "",
        "/* W17F: BOTH tables are pointer free on purpose. A pointer-valued initializer would move them",
        " * into .data.rel.ro and force R_X86_64_RELATIVE relocations into the artefact, and this",
        " * payload is entered without a dynamic loader (the build gate requires zero relocations).",
        " * The names are inline character arrays and the entry slices are plain indices, so the whole",
        " * table is const data with no relocation at all. */",
        "static const ps4rf_recipe_entry PS4RF_RECIPE_ENTRIES[] = {",
    ]
    first_by_recipe: dict[str, int] = {}
    for name in names:
        doc = recipes[name]
        first_by_recipe[name] = sum(len(recipes[n]["entries"]) for n in names[:names.index(name)])
        lines.append(f"  /* {name}: {doc['provenance']['source']} */")
        lines.append(f"  /* provenance sha256 {doc['provenance']['source_sha256']} */")
        recipe_id = names.index(name)
        for e in doc["entries"]:
            idx = e.get("index_source")
            index_source = INDEX_NAMES[idx] if idx else 0
            flags = FLAG_ATTACH_GATE if e["type"] == "FOLLOW_ONCE" else 0
            rva = e.get("rva", "0x0")
            lines.append(
                "  { \"%s\", %du, %du, %du, %uu, %uu, %uu, %sull, %uu, %uu },"
                % (e["name"], recipe_id, TYPE_IDS[e["type"]], e["length"],
                   e.get("root_index", 0), e.get("disp", 0), flags, rva, index_source,
                   e.get("max_index", 0)))
    lines.append("};")
    lines.append(f"#define PS4RF_RECIPE_ENTRY_COUNT "
                 f"{sum(len(d['entries']) for d in recipes.values())}u")
    lines.append("")
    lines.append("static const ps4rf_recipe_index PS4RF_RECIPE_INDEX_TABLE[] = {")
    for name in names:
        lines.append('  { "%s", %du, %du },'
                     % (name, first_by_recipe[name], len(recipes[name]["entries"])))
    lines.append("};")
    lines.append(f"#define PS4RF_RECIPE_TABLE_COUNT {len(names)}u")
    lines.append(f"#define PS4RF_RECIPE_TABLE_MAX_ENTRIES "
                 f"{max(len(d['entries']) for d in recipes.values())}u")
    lines.append("")
    lines.append("#endif /* PS4RF_RECIPE_DATA_H */")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    digest = hashlib.sha256(text.encode()).hexdigest()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"RECIPE DRIFT: {OUT} differs from the generated table")
            return 1
        if digest not in README.read_text():
            print("RECIPE PIN DRIFT: README.md does not carry the generated recipe hash")
            return 1
        print(f"recipe table OK  sha256={digest}")
        return 0
    OUT.write_text(text)
    if README.exists():
        body = README.read_text()
        if "recipe-table sha256" not in body:
            body += f"\n* recipe-table sha256: `{digest}` (native/target/ps4rf_recipe_data.h)\n"
        print(f"recipe table written  sha256={digest}")
        README.write_text(body)
    else:
        print(f"recipe table written  sha256={digest} (README missing)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
